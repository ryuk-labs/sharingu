// tools/make-arch-client.mjs — writes src/archclientdata.js: the Arch view's script, minified (sprint 5, A2).
//
//   node tools/make-arch-client.mjs          # regenerate src/archclientdata.js
//   node tools/make-arch-client.mjs --check  # exit 1 when src/archclientdata.js is not what the source makes
//
// src/archclient.js ARCH_CLIENT_SRC is the readable script (the view kit, the arch kit by its own source, the client);
// what the page ships is this file's ARCH_CLIENT, the same script through esbuild with WHITESPACE minification only:
// identifiers, structure and every string stay as written, so behavior is the source's, byte for byte in effect. The
// worker never runs esbuild (a dev dependency): the output is generated here, committed, and the gate runs --check so
// a source change that was not regenerated fails, as it does for src/doorcontract.js. The cap the page holds to (42 KB,
// tools/arch-selftest.mjs) is measured on what ships.
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import esbuild from "esbuild";
import { ARCH_CLIENT_SRC } from "../src/archclient.js";

const ENGINE = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(ENGINE, "src", "archclientdata.js");
const min = esbuild.transformSync(ARCH_CLIENT_SRC, { minifyWhitespace: true, legalComments: "none" }).code.replace(/\n$/, "");
const body = `// src/archclientdata.js — GENERATED by tools/make-arch-client.mjs from src/archclient.js ARCH_CLIENT_SRC. Do not edit:
// change the source and run \`node tools/make-arch-client.mjs\` (the gate runs --check and fails on drift).
export const ARCH_CLIENT = ${JSON.stringify(min)};
`;

if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur !== body) { console.log("✗ src/archclientdata.js is stale — run: node tools/make-arch-client.mjs"); process.exit(1); }
  console.log(`✓ src/archclientdata.js current (${min.length} bytes shipped, from ${ARCH_CLIENT_SRC.length} source)`);
  process.exit(0);
}
writeFileSync(OUT, body);
console.log(`wrote src/archclientdata.js: ${min.length} bytes shipped (from ${ARCH_CLIENT_SRC.length} source, -${ARCH_CLIENT_SRC.length - min.length})`);
