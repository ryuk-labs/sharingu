// tools/make-fonts.mjs — writes src/fontdata.js from engine/assets/fonts/*.woff2 (the look pass, sprint 2).
//
//   node tools/make-fonts.mjs          # regenerate src/fontdata.js
//   node tools/make-fonts.mjs --check  # exit 1 when src/fontdata.js is not what the fonts on disk make
//
// The three brand faces (Manrope, Fredoka, JetBrains Mono) are the website's own self-hosted woff2 files
// (~/batcave_vm/sharingu_website/assets/fonts, Latin subset, SIL Open Font License 1.1: the licence files sit beside
// them in engine/assets/fonts and travel with them). The worker serves them itself at GET /fonts/:file (src/fonts.js),
// so a page never asks Google for a font, and it works the same in `wrangler dev --local`, in a version upload and in
// the node selftests: the bytes ride the bundle as base64 (about 115 KB, well under the 3 MB free-plan limit), with no
// wrangler.jsonc change. FONT_VERSION is a hash of the bytes: the URL changes when a font does, so the one-year
// immutable cache is safe.
// The card's own cut faces (engine/assets/fonts/card/*.woff2, made by tools/make-card-fonts.py, sprint 12) ride the same
// file as CARD_FONT_B64: the MCP App card inlines them as data: URIs (src/previewcard.js); /fonts/ never serves them.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ENGINE = dirname(dirname(fileURLToPath(import.meta.url)));
const DIR = join(ENGINE, "assets", "fonts");
const OUT = join(ENGINE, "src", "fontdata.js");
const files = readdirSync(DIR).filter((f) => f.endsWith(".woff2")).sort();
const hash = createHash("sha256");
const rows = files.map((f) => {
  const bytes = readFileSync(join(DIR, f));
  hash.update(f).update(bytes);
  return `  ${JSON.stringify(f)}: ${JSON.stringify(bytes.toString("base64"))},`;
});
const CARD_DIR = join(DIR, "card");
const cardFiles = readdirSync(CARD_DIR).filter((f) => f.endsWith(".woff2")).sort();
const cardRows = cardFiles.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(CARD_DIR, f)).toString("base64"))},`);
const body = `// GENERATED by tools/make-fonts.mjs from engine/assets/fonts/*.woff2. Do not edit by hand: change the fonts, then run
// node tools/make-fonts.mjs. The faces are SIL Open Font License 1.1 (engine/assets/fonts/*-license.txt). src/fonts.js
// serves them at GET /fonts/:file.
export const FONT_VERSION = ${JSON.stringify(hash.digest("hex").slice(0, 10))};
export const FONT_B64 = {
${rows.join("\n")}
};
// the card's cut faces (engine/assets/fonts/card, tools/make-card-fonts.py): inlined by src/previewcard.js, never served
export const CARD_FONT_B64 = {
${cardRows.join("\n")}
};
`;
if (process.argv.includes("--check")) {
  let cur = ""; try { cur = readFileSync(OUT, "utf8"); } catch {}
  if (cur !== body) { console.error("src/fontdata.js is stale: run node tools/make-fonts.mjs"); process.exit(1); }
  console.log(`src/fontdata.js current (${files.length} faces)`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote src/fontdata.js: ${files.join(", ")} and the card's ${cardFiles.join(", ")} (${Math.round(body.length / 1024)} KB)`);
}
