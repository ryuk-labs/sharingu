// tools/make-presets.mjs — writes src/presetdata.js from engine/src/presets/*.md: the starter Broadcast built into the
// product (sprint 2, the owner's MCQ of 2026-09-30 evening and 2026-10-01: six agents, three workflows, three skills,
// versioned with the engine, the same shelf for every org; Equip copies one into a project).
//
//   node tools/make-presets.mjs          # regenerate src/presetdata.js
//   node tools/make-presets.mjs --check  # exit 1 when src/presetdata.js is not what the files on disk make
//
// One markdown file per item, a small front matter first (each line `key: value`):
//   kind     agent | workflow | skill (src/transmission.js ITEM_KINDS)
//   slug     [a-z0-9-]{2,40}, unique (src/transmission.js ITEM_SLUG's own rule)
//   order    the shelf's order, 1..n, unique
//   version  a whole number from 1: bump it when the item's text changes; a project that equipped an older version is
//            offered the update, never pushed it (QEBB5D318)
//   title    its name on the shelf; purpose its one line
//   calls    the MCP tools it uses, comma-separated: every one a tool of contracts/door.json, and exactly the tools its body
//            names in backticks (tools/presets-selftest.mjs holds both)
// then the body: the instruction set an AI client follows, in the small markdown src/markdown.js md() draws.
// The worker never reads the files: the bytes ride the bundle in src/presetdata.js (the fonts' and the contract's pattern),
// so a version upload, `wrangler dev --local` and the node selftests all read the same items.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ENGINE = dirname(dirname(fileURLToPath(import.meta.url)));
export const PRESET_DIR = join(ENGINE, "src", "presets");
export const PRESET_OUT = join(ENGINE, "src", "presetdata.js");
export const PRESET_FIELDS = ["kind", "slug", "order", "version", "title", "purpose", "calls"];

// parsePreset(text, file) -> { kind, slug, order, version, title, purpose, calls, body } | throws naming the file and the field
export function parsePreset(text, file = "?") {
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(String(text).replace(/\r\n/g, "\n"));
  if (!m) throw new Error(`${file}: no front matter (a --- line, key: value lines, a --- line, then the body)`);
  const fm = {};
  for (const line of m[1].split("\n")) {
    if (!line.trim()) continue;
    const kv = /^([a-z]+):\s*(.*)$/.exec(line);
    if (!kv) throw new Error(`${file}: a front matter line is not "key: value": ${line.slice(0, 60)}`);
    if (!PRESET_FIELDS.includes(kv[1])) throw new Error(`${file}: an unknown front matter key "${kv[1]}"`);
    fm[kv[1]] = kv[2].trim();
  }
  for (const k of PRESET_FIELDS) if (!fm[k]) throw new Error(`${file}: the front matter has no ${k}`);
  const order = Number(fm.order), version = Number(fm.version);
  if (!Number.isInteger(order) || order < 1) throw new Error(`${file}: order is not a whole number from 1`);
  if (!Number.isInteger(version) || version < 1) throw new Error(`${file}: version is not a whole number from 1`);
  return { kind: fm.kind, slug: fm.slug, order, version, title: fm.title, purpose: fm.purpose,
    calls: fm.calls.split(",").map((x) => x.trim()).filter(Boolean), body: m[2].trim() + "\n" };
}

// readPresets() -> the parsed items, in shelf order
export function readPresets() {
  return readdirSync(PRESET_DIR).filter((f) => f.endsWith(".md")).sort()
    .map((f) => ({ ...parsePreset(readFileSync(join(PRESET_DIR, f), "utf8"), f), file: f }))
    .sort((a, b) => a.order - b.order);
}

// presetDataOf(items) -> the module text of src/presetdata.js
export function presetDataOf(items) {
  const rows = items.map(({ file, ...p }) => p);
  const hash = createHash("sha256").update(JSON.stringify(rows)).digest("hex").slice(0, 10);
  return `// GENERATED by tools/make-presets.mjs from engine/src/presets/*.md. Do not edit by hand: change a file there, then run
// node tools/make-presets.mjs. The starter Broadcast built into the product (src/starter.js reads it): the same shelf for
// every org, versioned with the engine.
export const PRESETS_HASH = ${JSON.stringify(hash)};
export const PRESETS = ${JSON.stringify(rows, null, 1)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const items = readPresets();
  const body = presetDataOf(items);
  if (process.argv.includes("--check")) {
    let cur = ""; try { cur = readFileSync(PRESET_OUT, "utf8"); } catch {}
    if (cur !== body) { console.error("src/presetdata.js is stale: run node tools/make-presets.mjs"); process.exit(1); }
    console.log(`src/presetdata.js current (${items.length} items)`);
  } else {
    writeFileSync(PRESET_OUT, body);
    console.log(`wrote src/presetdata.js: ${items.map((p) => p.slug).join(", ")} (${Math.round(body.length / 1024)} KB)`);
  }
}
