// the four MCP annotations, in words (the connector directory reads them: docs/plan/MARKETPLACE.md M0)
function hintWords(a) {
  if (!a) return "";
  const w = [];
  if (a.readOnlyHint) w.push("read-only"); else w.push(a.destructiveHint ? "destructive" : "not destructive");
  if (a.idempotentHint) w.push("idempotent");
  w.push(a.openWorldHint ? "open world" : "closed world");
  return w.join(" · ");
}
