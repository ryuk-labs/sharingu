// the one MCP address: the plugin's own (plugin/.mcp.json, 9.1: one server, http, no header)
export function mcpAddress() {
  const mj = JSON.parse(readFileSync(join(REPO, "plugin", ".mcp.json"), "utf8"));
  const servers = Object.values(mj.mcpServers || {});
  if (servers.length !== 1 || !servers[0].url) throw new Error("plugin/.mcp.json: one server with a url wanted");
  return servers[0].url;
}

// the contract's inventory (contracts/door.json), the object GET /capabilities serves
export function contractInventory() {
  const inv = JSON.parse(readFileSync(join(REPO, "contracts", "door.json"), "utf8")).inventory;
  if (!inv || !Array.isArray(inv.tools) || !Array.isArray(inv.routes)) throw new Error("contracts/door.json holds no inventory");
  return { note: inv.note, tools: inv.tools, routes: inv.routes, failures: inv.failures || {} };
}
// inventoryOf(answer) -> a GET /capabilities answer without what is the reader's own (you, each row's callable)
export function inventoryOf(j) {
  const strip = (row) => { const { callable, ...rest } = row || {}; return rest; };
  return { note: j.note, tools: (j.tools || []).map(strip), routes: (j.routes || []).map(strip), failures: j.failures || {} };
}
