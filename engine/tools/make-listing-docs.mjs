//   node tools/make-listing-docs.mjs --url <worker> --creds <file>   # from a worker's GET /capabilities (the brief's source)
//   node tools/make-listing-docs.mjs                                 # from contracts/door.json `inventory` (no worker)
//   node tools/make-listing-docs.mjs --check                         # exit 1 when listing/docs.html is not what the contract
//                                                                    #   makes now (the gate's step, beside 9.1's)
//
// The two sources are ONE: GET /capabilities serves contracts/door.json `inventory` (tools/make-door-contract.py writes
// it, the gate regenerates and diffs it) with the reader's own `you` and each row's `callable` beside it; this tool drops
// those two (they are per reader) and, with --url, REFUSES to write when what is left differs from the contract (a worker
// running other code than this checkout's): the page is always the contract's, so --check needs no worker. The smoke
// (tools/smoke/s51-listing.mjs) proves the worker's answer equals the contract on its own worker.
// --creds: a credentials.env with an *_AGENT_R_OWNER_KEY= line (or the bare key); the key rides a bearer header and is
// never printed. The output is deterministic: the same contract and address make the same bytes (no date in it).
