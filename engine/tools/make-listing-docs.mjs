// checkDocs(path) -> { ok, why, tools, routes } — listing/docs.html against what the contract makes now
export function checkDocs(path = DOCS_PAGE) {
  const inv = contractInventory();
  let cur = null; try { cur = readFileSync(path, "utf8"); } catch {}
  const want = renderDocs(inv, mcpAddress());
  const why = cur === null ? "missing" : cur !== want ? "differs from what the contract makes" : "";
  return { ok: !why, why, tools: inv.tools.length, routes: inv.routes.length };
}

async function fromWorker(url, credsPath) {
  const t = readFileSync(credsPath, "utf8");
  const key = ((t.match(/^[A-Z0-9_]*_AGENT_R_OWNER_KEY=["']?([^"'\s]+)/m) || [])[1]) || t.trim();
  if (!key || /\s/.test(key)) throw new Error(`${credsPath}: no *_AGENT_R_OWNER_KEY= line and not a bare key`);
  const r = await fetch(String(url).replace(/\/+$/, "") + "/capabilities", { headers: { accept: "application/json", authorization: "Bearer " + key } });
  if (r.status !== 200) throw new Error(`GET /capabilities: HTTP ${r.status}`);
  return inventoryOf(await r.json());
}

// run directly? (REAL paths compared: engine/CLAUDE.md's scar)
const real = (f) => { try { return realpathSync(f); } catch { return f; } };
if (process.argv[1] && real(fileURLToPath(import.meta.url)) === real(process.argv[1])) {
  const argv = process.argv.slice(2);
  const flag = (n) => { const i = argv.indexOf(n); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[i + 1] : undefined; };
  try {
    if (argv.includes("--check")) {
      const r = checkDocs();
      if (!r.ok) { console.error(`listing/docs.html ${r.why}: run node tools/make-listing-docs.mjs`); process.exit(1); }
      console.log(`listing/docs.html current (${r.tools} tools, ${r.routes} routes from contracts/door.json)`);
    } else {
      const contract = contractInventory();
      let inv = contract, from = "contracts/door.json";
      if (flag("--url")) {
        if (!flag("--creds")) { console.error("usage: node tools/make-listing-docs.mjs [--url <worker> --creds <file>] | --check"); process.exit(2); }
        inv = await fromWorker(flag("--url"), flag("--creds"));
        if (!sameInventory(inv, contract)) {
          console.error(`refused (nothing written): ${flag("--url")}'s GET /capabilities differs from contracts/door.json's inventory — the worker runs other code than this checkout (regenerate the contract: python3 tools/make-door-contract.py, or start the worker from this checkout)`);
          process.exit(1);
        }
        from = `${flag("--url")} GET /capabilities (equal to contracts/door.json's inventory)`;
      }
      mkdirSync(dirname(DOCS_PAGE), { recursive: true });
      writeFileSync(DOCS_PAGE, renderDocs(inv, mcpAddress()));
      console.log(`wrote listing/docs.html from ${from}: ${inv.tools.length} tools, ${inv.routes.length} routes`);
    }
  } catch (e) { console.error(`✗ ${String((e && e.message) || e)}`); process.exit(1); }
}
