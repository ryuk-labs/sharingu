// tools/make-front-assets.mjs — writes src/frontassetdata.js from engine/assets/walkthrough/*.jpg, engine/assets/clients/*.png and
// engine/assets/brand/*.png (sprint 21, 21.P: the front door's pictures, the way tools/make-fonts.mjs bundles the faces; 21.4a: U-chan's
// mark as a PNG, brand/uchan-mark.png — src/ui.js uchan's own vector rendered at twice its 30px email size — the one image an email
// carries, src/mails.js; 21.4c: Google's own G mark, clients/google.png — Google's published sign-in-button vector rendered at 48px
// — beside "Continue with Google", src/googlepage.js).
//
//   node tools/make-front-assets.mjs          # regenerate src/frontassetdata.js
//   node tools/make-front-assets.mjs --check  # exit 1 when src/frontassetdata.js is not what the files on disk make
//
// The walkthrough's five posters are the website's own JPEGs (~/batcave_vm/sharingu_website/assets/walkthrough, the stills its
// docs page shows behind each video) and the two client logos its own (assets/clients/claude.png, chatgpt.png), copied here
// by hand, never hotlinked: the worker serves them itself at GET /assets/<dir>/<file> (src/frontassets.js), so a front page
// asks nobody else for a picture, and it works the same in `wrangler dev --local`, a version upload and the node selftests.
// The bytes ride the bundle as base64 (about 360 KB). FRONT_ASSET_VERSION is a hash of the bytes: the URL changes when a
// picture does, so the one-year immutable cache is safe.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ENGINE = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(ENGINE, "src", "frontassetdata.js");
const DIRS = [["walkthrough", ".jpg"], ["clients", ".png"], ["brand", ".png"]];
const hash = createHash("sha256");
const rows = [];
for (const [dir, ext] of DIRS) {
  for (const f of readdirSync(join(ENGINE, "assets", dir)).filter((x) => x.endsWith(ext)).sort()) {
    const bytes = readFileSync(join(ENGINE, "assets", dir, f));
    hash.update(`${dir}/${f}`).update(bytes);
    rows.push(`  ${JSON.stringify(`${dir}/${f}`)}: ${JSON.stringify(bytes.toString("base64"))},`);
  }
}
const body = `// GENERATED by tools/make-front-assets.mjs from engine/assets/walkthrough/*.jpg, engine/assets/clients/*.png and engine/assets/brand/*.png. Do not edit by
// hand: change the pictures, then run node tools/make-front-assets.mjs. src/frontassets.js serves them at GET /assets/<path>.
export const FRONT_ASSET_VERSION = ${JSON.stringify(hash.digest("hex").slice(0, 10))};
export const FRONT_ASSET_B64 = {
${rows.join("\n")}
};
`;
if (process.argv.includes("--check")) {
  let cur = ""; try { cur = readFileSync(OUT, "utf8"); } catch {}
  if (cur !== body) { console.error("src/frontassetdata.js is stale: run node tools/make-front-assets.mjs"); process.exit(1); }
  console.log(`src/frontassetdata.js current (${rows.length} pictures)`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote src/frontassetdata.js: ${rows.length} pictures (${Math.round(body.length / 1024)} KB)`);
}
