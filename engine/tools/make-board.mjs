function shotsHtml() {
  const have = existsSync(SHOTS_DIR) ? new Set(readdirSync(SHOTS_DIR)) : new Set();
  const figs = SHOT_PAGES.map(([page, title]) => {
    const imgs = SHOT_VARIANTS.map(([th, w, label]) => {
      const f = `${page}-${th}-${w}.jpg`;
      if (!have.has(f)) return `<div class="noshot">${esc(label)}: not taken yet (<code>--shots</code>)</div>`;
      const b = readFileSync(join(SHOTS_DIR, f));
      const [iw, ih] = jpegSize(b);
      return `<figure class="${w < 600 ? "ph" : "dk"}"><button type="button" class="zoom" aria-label="${esc(`${title}, ${label}: open larger`)}"><img alt="${esc(`${title}, ${label}`)}" width="${iw}" height="${ih}" src="data:image/jpeg;base64,${b.toString("base64")}"></button><figcaption>${esc(label)}</figcaption></figure>`;
    });
    return `<div class="shot" id="shot-${esc(page)}"><h3>${esc(title)}</h3><div class="shotrow">${imgs.join("")}</div></div>`;
  });
  return figs.join("");
}
function jpegSize(b) {
  let i = 2;
  while (i < b.length) {
    if (b[i] !== 0xff) { i++; continue; }
    const m = b[i + 1], len = b.readUInt16BE(i + 2);
    if (m >= 0xc0 && m <= 0xc3) return [b.readUInt16BE(i + 7), b.readUInt16BE(i + 5)];
    i += 2 + len;
  }
  return [0, 0];
}
