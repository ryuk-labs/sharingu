// part(mdText, heading) -> the text under the heading (to the next heading of its level or higher); heading: a string the
// heading's text starts with, or a RegExp. Throws when the heading is gone (the generator names what moved).
function part(text, heading, { withHeading = false, file = "" } = {}) {
  const lines = text.split("\n");
  let at = -1, level = 0;
  for (let i = 0; i < lines.length; i++) {
    const m = /^(#{1,6})\s+(.*)$/.exec(lines[i]);
    if (!m) continue;
    const hit = heading instanceof RegExp ? heading.test(m[2]) : m[2].startsWith(heading);
    if (hit) { at = i; level = m[1].length; break; }
  }
  if (at < 0) throw new Error(`make-board: no heading "${heading}" in ${file || "the source"} (the board reads it: update tools/make-board.mjs)`);
  let end = lines.length;
  for (let i = at + 1; i < lines.length; i++) { const m = /^(#{1,6})\s/.exec(lines[i]); if (m && m[1].length <= level) { end = i; break; } }
  return lines.slice(withHeading ? at : at + 1, end).join("\n").trim();
}
// between(text, from, to) -> the text from the line holding `from` up to (not including) the line holding `to`
function between(text, from, to, file) {
  const a = text.indexOf(from);
  if (a < 0) throw new Error(`make-board: "${from}" is gone from ${file} (update tools/make-board.mjs)`);
  const b = to ? text.indexOf(to, a + from.length) : -1;
  return text.slice(text.lastIndexOf("\n", a) + 1, b < 0 ? undefined : text.lastIndexOf("\n", b) + 1).trim();
}
// bullets(text) -> the top-level "- " items, each with its continuation lines: [{ label, body, raw }]
function bullets(text) {
  const out = [];
  for (const line of text.split("\n")) {
    if (/^- /.test(line)) out.push(line.slice(2));
    else if (out.length && /^\s+\S/.test(line)) out[out.length - 1] += " " + line.trim();
  }
  return out.map((raw) => { const m = /^\*\*(.+?)\*\*:?\s*(.*)$/.exec(raw); return { label: m ? m[1].replace(/:$/, "") : "", body: m ? m[2] : raw, raw }; });
}
// rows(tableText) -> the table's rows (cells trimmed; an escaped \| stays in its cell)
function rows(text) {
  return text.split("\n").filter((l) => /^\|.*\|\s*$/.test(l.trim())).map((l) => l.trim().replace(/\\\|/g, "\u0002").slice(1, -1).split("|").map((c) => c.trim().replace(/\u0002/g, "|")))
    .filter((r) => !r.every((c) => /^:?-{3,}:?$/.test(c)));
}

// ---- markdown, the product's own renderer (src/markdown.js md) with fenced code, links and the escaped pipe added ----
function inl(s) {
  return esc(s).replace(/`([^`]+)`/g, "<code>$1</code>").replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>")
    .replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '<a href="$2" rel="noopener">$1</a>');
}
function mdx(text) {
  const out = []; let prose = [], code = null;
  const flush = () => {
    if (!prose.length) return;
    const t = prose.join("\n").replace(/\\\|/g, "\u0002").replace(/^#{4,6}\s/gm, "### ");
    out.push(md(t).replace(/\u0002/g, "|").replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '<a href="$2" rel="noopener">$1</a>'));
    prose = [];
  };
  for (const line of String(text).split("\n")) {
    if (/^\s*```/.test(line)) {
      if (code) { out.push(`<pre><code>${esc(code.join("\n"))}</code></pre>`); code = null; } else { flush(); code = []; }
      continue;
    }
    if (code) code.push(line); else prose.push(line);
  }
  if (code) out.push(`<pre><code>${esc(code.join("\n"))}</code></pre>`);
  flush();
  return out.join("\n");
}

