// ---- the self-check: nothing shaped like a secret, a code or an applicant's address ----
export function selfCheck(html) {
  const t = html.replace(/data:[a-z]+\/[a-z0-9.+-]+;base64,[A-Za-z0-9+/=]+/g, "");
  const found = [];
  const rules = [
    ["a 40-hex key", /\b[0-9a-f]{40}\b/i],
    ["a sign-in code", /\bcode:\s*[A-Z0-9]{4,}(?:-[A-Z0-9]{4,}){2,}/],
    ["a code: line", /(^|\n)\s*code:\s*\S/],
    ["an sk- token", /\bsk-[A-Za-z0-9_-]{8,}/],
    ["a ghp_ token", /\bghp_[A-Za-z0-9]{8,}/],
    ["a github_pat_ token", /\bgithub_pat_[A-Za-z0-9_]{8,}/],
    ["a gmail address", /[A-Za-z0-9._%+-]+@(gmail|googlemail)\.com\b/i],
  ];
  for (const [what, re] of rules) { const m = re.exec(t); if (m) found.push(`${what} near "${t.slice(Math.max(0, m.index - 30), m.index).replace(/\s+/g, " ")}…"`); }
  for (const m of t.matchAll(EMAIL)) if (!OWN_MAIL.test(m[1])) { found.push(`an address on ${m[1]}`); break; }
  return found;
}

export function checkBoard(file = BOARD) {
  if (!existsSync(file)) return { ok: false, why: `${rel(file)} does not exist — run: node tools/make-board.mjs` };
  const have = readFileSync(file, "utf8");
  const leaks = selfCheck(have);
  if (leaks.length) return { ok: false, why: `${rel(file)} holds ${leaks.join("; ")}` };
  const want = renderBoard();
  if (have.replace(STAMP_RE, "") !== want.replace(STAMP_RE, "")) return { ok: false, why: `${rel(file)} is not what the sources make now — run: node tools/make-board.mjs` };
  return { ok: true, bytes: Buffer.byteLength(have) };
}

